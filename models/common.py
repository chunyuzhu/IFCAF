class MambaWithNormBlock(nn.Module):
    def __init__(self, dim, bimamba_type=None, RMS=False):
        super(MambaWithNormBlock, self).__init__()
        self.norm = RMSNorm(dim) if RMS else LayerNorm(dim, 'with_bias')
        self.mamba = Mamba(dim, bimamba_type=bimamba_type)

    def forward(self, x):
        return self.mamba(self.norm(x)) + x

class MambaBlock(nn.Module):
    def __init__(self, dim, drop=0.1, attn_drop=0., RMSnorm=True):
        super(MambaBlock, self).__init__()
        self.encoder = MambaWithNormBlock(dim, bimamba_type="v2", RMS=RMSnorm)
        # self.encoder = Block(dim, num_heads=8, drop=drop, attn_drop=attn_drop)
    def forward(self, x):
        x = self.encoder(x)
        return x

class FusionConcat(nn.Module):
    def __init__(self, weight=0.5):
        super().__init__()
        self.w = weight
    """F = cat([Fr, Ft], dim=1)"""
    def forward(self, x):
        return torch.cat([x[0], x[1]], dim=1)

class FusionConcat1x1(nn.Module):
    """cat + 1x1 conv 压缩通道（常见轻量 CNN 融合）"""
    def __init__(self, c, out_c=None):
        super().__init__()
        out_c = out_c or c
        self.proj = nn.Conv2d(2 * c, out_c, kernel_size=1, bias=False)
        self.bn = nn.BatchNorm2d(out_c)
        self.act = nn.SiLU(inplace=True)

    def forward(self, x):
        F = torch.cat([x[0], x[1]], dim=1)
        return self.act(self.bn(self.proj(F)))

class FusionSum(nn.Module):
    """F = Fr + Ft"""
    def forward(self, fr, ft):
        return fr + ft

class FusionWeightedSum(nn.Module):
    """F = a*Fr + (1-a)*Ft，其中 a 是可学习标量（极轻量）"""
    def __init__(self, init=0.5):
        super().__init__()
        self.logit = nn.Parameter(torch.tensor(float(init)).logit())

    def forward(self, fr, ft):
        a = torch.sigmoid(self.logit)
        return a * fr + (1 - a) * ft

class FusionGated(nn.Module):
    """门控融合：gate = sigmoid(conv1x1(cat)); F = gate*Fr + (1-gate)*Ft"""
    def __init__(self, c):
        super().__init__()
        self.gate = nn.Conv2d(2 * c, c, kernel_size=1, bias=True)

    def forward(self, x):
        g = torch.sigmoid(self.gate(torch.cat([x[0], x[1]], dim=1)))
        return g * x[0] + (1 - g) * x[1]

# 可选：超轻量通道注意力（ECA风格，避免SE的两层FC也可）
class FusionECA(nn.Module):
    """ECA-like channel attention on concat -> reweight then 1x1 fuse"""
    def __init__(self, c, k=3):
        super().__init__()
        self.pool = nn.AdaptiveAvgPool2d(1)
        self.conv1d = nn.Conv1d(1, 1, kernel_size=k, padding=(k-1)//2, bias=False)
        self.proj = nn.Conv2d(2 * c, c, kernel_size=1, bias=False)

    def forward(self, x):
        x = torch.cat([x[0], x[1]], dim=1)   # [B,2C,H,W]
        y = self.pool(x).squeeze(-1).transpose(1,2)  # [B,1,2C]
        y = torch.sigmoid(self.conv1d(y)).transpose(1,2).unsqueeze(-1)  # [B,2C,1,1]
        x = x * y
        return self.proj(x)

class CoordAwareResample(nn.Module):
    """坐标感知的特征缩放模块"""

    def __init__(self, in_dim, scale_type):
        super().__init__()
        self.scale_type = scale_type
        out_dim = {
            'down2': in_dim // 2,
            'down4': in_dim // 4,
            'up2': in_dim * 2,
            'up4': in_dim * 4
        }[scale_type]

        # 坐标编码MLP (x,y) + 特征 → 新特征
        # self.kan = KANLinear(in_dim + 2, out_dim)
        self.mlp = MLP(in_dim + 2, out_dim, [256,128])
        self.norm = nn.LayerNorm(in_dim)

    def forward(self, x):
        B, C, H, W = x.shape
        # 生成标准化坐标 [-1,1] 范围
        coord = make_coord((H, W), flatten=False).to(x.device).unsqueeze(0).repeat(B, 1, 1, 1)  # [B,H,W,2]

        # 特征与坐标拼接
        x = self.norm(x.permute(0, 2, 3, 1))  # [B,H,W,C]
        feat_coord = torch.cat([x, coord], dim=-1) # [B,H,W,C+2]

        # 特征变换
        out = self.mlp(feat_coord).permute(0, 3, 1, 2)  # [B,C',H,W]
        return out

class INF_MAM(nn.Module):
    def __init__(self, d_model,
                 n_layer=2, vert_anchors=8, horz_anchors=8,
                 embd_pdrop=0.1, attn_pdrop=0.1, resid_pdrop=0.1):
        super(INF_MAM, self).__init__()

        self.n_embd = d_model
        self.vert_anchors = vert_anchors
        self.horz_anchors = horz_anchors

        self.pos_emb = nn.Parameter(torch.zeros(1, 3 * vert_anchors * horz_anchors, self.n_embd))
        self.mamba_blocks = nn.Sequential(*[MambaBlock(dim=self.n_embd, RMSnorm=False)
                                            for layer in range(n_layer)])
        self.channel_downsample2x = CoordAwareResample(d_model, 'down2')
        self.channel_downsample4x = CoordAwareResample(d_model, 'down4')
        self.channel_upsample2x = CoordAwareResample(d_model // 2, 'up2')
        self.channel_upsample4x = CoordAwareResample(d_model // 4, 'up4')
        self.ln_f = nn.LayerNorm(self.n_embd)

        self.drop = nn.Dropout(embd_pdrop)
        self.avgpool = LearnableWeightAdaptivePool(self.vert_anchors, self.horz_anchors)
        self.apply(self._init_weights)

    @staticmethod
    def _init_weights(module):
        if isinstance(module, nn.Linear):
            module.weight.data.normal_(mean=0.0, std=0.02)
            if module.bias is not None:
                module.bias.data.zero_()
        elif isinstance(module, nn.LayerNorm):
            module.bias.data.zero_()
            module.weight.data.fill_(1.0)

    def forward(self, fea):
        """
        Args:
            x (tuple?)
        """
        fea1 = fea[0]
        fea2 = fea[1]
        fea3 = fea[2]

        shape = [fea1.shape, fea2.shape, fea3.shape]  # bs, c, h, w
        bs = shape[0][0]

        fea1 = self.avgpool(fea1)
        fea2 = self.avgpool(fea2)
        fea3 = self.avgpool(fea3)

        fea1 = self.channel_upsample4x(fea1)
        fea2 = self.channel_upsample2x(fea2)

        fea1 = fea1.view(shape[0][0], self.n_embd, -1)
        fea2 = fea2.view(shape[1][0], self.n_embd, -1)
        fea3 = fea3.view(shape[2][0], self.n_embd, -1)

        token = torch.cat([fea1, fea2, fea3], dim=2)
        token = token.permute(0, 2, 1).contiguous()  # dim:(B, 3*H*W, C)

        x = self.drop(self.pos_emb + token)  # sum positional embedding and token    dim:(B, 2*H*W, C)
        # residual = None
        # x, residual = self.mamba_blocks((x, residual))  # dim:(B, 3*H*W, C)
        # x = x + residual
        x = self.mamba_blocks(x)
        x = self.ln_f(x)  # dim:(B, 3*H*W, C)

        x = x.view(bs, 3, self.vert_anchors, self.horz_anchors, self.n_embd)
        x = x.permute(0, 1, 4, 2, 3)  # dim:(B, 3, C, H, W)

        fea1_out = x[:, 0, :, :, :].contiguous().view(bs, self.n_embd, self.vert_anchors, self.horz_anchors)
        fea2_out = x[:, 1, :, :, :].contiguous().view(bs, self.n_embd, self.vert_anchors, self.horz_anchors)
        fea3_out = x[:, 2, :, :, :].contiguous().view(bs, self.n_embd, self.vert_anchors, self.horz_anchors)

        fea1_out = self.channel_downsample4x(fea1_out)
        fea2_out = self.channel_downsample2x(fea2_out)
        # -------------------------------------------------------------------------
        # Interpolate (or Upsample)
        # -------------------------------------------------------------------------
        fea1_out = F.interpolate(fea1_out, size=([shape[0][2], shape[0][3]]), mode='bilinear')
        fea2_out = F.interpolate(fea2_out, size=([shape[1][2], shape[1][3]]), mode='bilinear')
        fea3_out = F.interpolate(fea3_out, size=([shape[2][2], shape[2][3]]), mode='bilinear')

        fea1_out = fea1_out + fea[0]
        fea2_out = fea2_out + fea[1]
        fea3_out = fea3_out + fea[2]

        return fea1_out, fea2_out, fea3_out

def to_3d(x):
    return rearrange(x, 'b c h w -> b (h w) c')

def to_4d(x, h, w):
    return rearrange(x, 'b (h w) c -> b c h w', h=h, w=w)

class BiasFree_LayerNorm(nn.Module):
    def __init__(self, normalized_shape):
        super(BiasFree_LayerNorm, self).__init__()
        if isinstance(normalized_shape, numbers.Integral):
            normalized_shape = (normalized_shape,)
        normalized_shape = torch.Size(normalized_shape)

        assert len(normalized_shape) == 1

        self.weight = nn.Parameter(torch.ones(normalized_shape))
        self.normalized_shape = normalized_shape

    def forward(self, x):
        sigma = x.var(-1, keepdim=True, unbiased=False)
        return x / torch.sqrt(sigma+1e-5) * self.weight

class WithBias_LayerNorm(nn.Module):
    def __init__(self, normalized_shape):
        super(WithBias_LayerNorm, self).__init__()
        if isinstance(normalized_shape, numbers.Integral):
            normalized_shape = (normalized_shape,)
        normalized_shape = torch.Size(normalized_shape)

        assert len(normalized_shape) == 1

        self.weight = nn.Parameter(torch.ones(normalized_shape))
        self.bias = nn.Parameter(torch.zeros(normalized_shape))
        self.normalized_shape = normalized_shape

    def forward(self, x):
        mu = x.mean(-1, keepdim=True)
        sigma = x.var(-1, keepdim=True, unbiased=False)
        return (x - mu) / torch.sqrt(sigma+1e-5) * self.weight + self.bias

class LayerNorm(nn.Module):
    def __init__(self, dim, LayerNorm_type):
        super(LayerNorm, self).__init__()
        if LayerNorm_type =='BiasFree':
            self.body = BiasFree_LayerNorm(dim)
        else:
            self.body = WithBias_LayerNorm(dim)

    def forward(self, x):
        if len(x.shape)==4:
            h, w = x.shape[-2:]
            return to_4d(self.body(to_3d(x)), h, w)
        else:
            return self.body(x)

class INFAF(nn.Module):

    def __init__(self,
                 feat_dim,
                 local_ensemble=True,
                 hidden_list=[256, 128],
                 feat_unfold=False,
                 scale_token=True):
        super().__init__()
        self.local_ensemble = local_ensemble
        self.feat_unfold = feat_unfold
        self.scale_token = scale_token
        self.head = 8

        self.feat_dim = feat_dim
        self.imnet = MLP(2, out_dim=feat_dim // self.head, hidden_list=hidden_list)
        self.concat = Concat(dimension=1)
        self.conv1x1_out = Conv(c1=feat_dim * 2, c2=feat_dim, k=1, s=1, p=0, g=1, act=True)
        self.attn_drop = nn.Dropout(0.1)

    def forward(self, x):
        feat_vis = x[0]
        feat_ir = x[1]
        assert feat_vis.shape[0] == feat_ir.shape[0]
        bs, c, h, w = feat_vis.shape

        if self.feat_unfold:
            feat_vis = F.unfold(feat_vis, 1, padding=1).view(
                feat_vis.shape[0], feat_vis.shape[1] * 9, feat_vis.shape[2], feat_vis.shape[3])
            feat_ir = F.unfold(feat_ir, 1, padding=1).view(
                feat_ir.shape[0], feat_ir.shape[1] * 9, feat_ir.shape[2], feat_ir.shape[3])
        coord = make_coord([h, w]).cuda().unsqueeze(0).expand(bs, -1, -1)
        # coord = make_coord([h, w]).cuda().unsqueeze(0).expand(bs, -1, -1)
        coord_ = coord.clone()
        coord_ = coord_.unsqueeze(2)  # b q 1 2

        feat_coord = make_coord(feat_vis.shape[-2:], flatten=False).cuda() \
            .permute(2, 0, 1) \
            .unsqueeze(0).expand(feat_vis.shape[0], 2, *feat_vis.shape[-2:])  # b 2 h w
        bs, q = coord_.shape[:2]
        coord_k = F.grid_sample(feat_coord, coord_.flip(-1), mode='nearest', align_corners=False).expand(bs, 2, q, feat_vis.shape[1]).permute(0, 2, 1, 3)  # b q 1 2
        Q = coord_k.reshape(bs, q, 2, self.head, self.feat_dim // self.head).permute(0, 1, 3, 4, 2)  # b q h c 2
        K_inf = F.grid_sample(feat_ir, coord_.flip(-1), mode='bilinear', align_corners=False).permute(0, 2, 3, 1).half()
        K_inf = K_inf.reshape(bs, q, 1, self.head, self.feat_dim // self.head).permute(0, 1, 3, 2, 4)  # b q h 1 c
        K_vis = F.grid_sample(feat_vis, coord_.flip(-1), mode='bilinear', align_corners=False).permute(0, 2, 3, 1).half()
        K_vis = K_vis.reshape(bs, q, 1, self.head, self.feat_dim // self.head).permute(0, 1, 3, 2, 4)  # b q h 1 c
        attn_vis = torch.matmul(K_vis, Q) / np.sqrt(self.feat_dim // self.head) # b q h 1 2
        attn_vis = torch.softmax(attn_vis, -1)
        attn_vis = self.attn_drop(attn_vis).permute(0, 1, 3, 2, 4) # b q 1 h 2
        attn_vis = self.imnet(attn_vis.view(bs * q * self.head,-1)).view(bs * q, self.head,
                                                                         self.feat_dim // self.head) # b*q h c
        V_vis = F.grid_sample(feat_vis, coord_.flip(-1), mode='bilinear', align_corners=False).permute(0, 2, 1, 3).half() # b q c 1
        V_vis = V_vis.reshape(bs, q, self.head, self.feat_dim // self.head) #  b q h c
        # pred_vis = torch.mul(V_vis.contiguous().view(bs * q, self.head, -1), attn_vis).view(bs, q, -1)
        attn_inf = torch.matmul(K_inf, Q) / np.sqrt(self.feat_dim // self.head)  # b q h 1 2
        attn_inf = torch.softmax(attn_inf, -1)
        attn_inf = self.attn_drop(attn_inf).permute(0, 1, 3, 2, 4)  # b q 1 h 2
        attn_inf = self.imnet(attn_inf.view(bs * q * self.head, -1)).view(bs * q, self.head,
                                                                          self.feat_dim // self.head)  # b*q h c
        V_inf = F.grid_sample(feat_ir, coord_.flip(-1), mode='bilinear', align_corners=False).permute(0, 2, 1, 3)  # b q c 1
        V_inf = V_inf.reshape(bs, q, self.head, self.feat_dim // self.head)  # b q h c
        pred_vis = torch.mul(V_vis.contiguous().view(bs * q, self.head, -1), attn_inf).view(bs, q, -1).permute(0, 2,
                                                                                                               1).view(bs, -1, h, w)
        pred_inf = torch.mul(V_inf.contiguous().view(bs * q, self.head, -1), attn_vis).view(bs, q, -1).permute(0, 2, 1).view(bs, -1, h, w)
        return pred_vis,pred_inf
